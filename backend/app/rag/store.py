"""On-disk vector index: chunks.jsonl + vectors.npy + meta.json under data/index/advisories/.

Generated by scripts/build_index.py (needs the proxy for embeddings); git-ignored, rebuildable from the
committed raw text.
"""

import json
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np


@dataclass(frozen=True)
class StoredChunk:
    id: str
    doc_id: str
    text: str
    title: str
    source: str
    url: str


@dataclass
class Index:
    chunks: list[StoredChunk]
    vectors: np.ndarray  # (n, 1024), L2-normalised
    meta: dict

    def save(self, path: Path) -> None:
        path.mkdir(parents=True, exist_ok=True)
        (path / "chunks.jsonl").write_text(
            "".join(json.dumps(asdict(c), ensure_ascii=False) + "\n" for c in self.chunks), encoding="utf-8"
        )
        np.save(path / "vectors.npy", self.vectors)
        (path / "meta.json").write_text(json.dumps(self.meta, ensure_ascii=False, indent=1), encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> "Index":
        lines = (path / "chunks.jsonl").read_text(encoding="utf-8").splitlines()
        chunks = [StoredChunk(**json.loads(line)) for line in lines if line.strip()]
        vectors = np.load(path / "vectors.npy")
        meta = json.loads((path / "meta.json").read_text(encoding="utf-8"))
        if len(chunks) != len(vectors):
            raise ValueError(f"index at {path} is inconsistent: {len(chunks)} chunks vs {len(vectors)} vectors")
        return cls(chunks, vectors, meta)
